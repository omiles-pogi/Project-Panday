/** The PDFs are rendered on the phone from data the app already has, then handed to the share sheet. */
export async function sharePdf(html: string, title: string): Promise<void> {
  if (!(await Sharing.isAvailableAsync())) {
    throw new Error("Sharing isn't available on this device, so the PDF can't be saved.");
  }
  const { uri } = await Print.printToFileAsync({ html });
  await Sharing.shareAsync(uri, { mimeType: "application/pdf", dialogTitle: title, UTI: "com.adobe.pdf" });
}

const esc = (value: string | number | null | undefined) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const STYLE = `
  body { font-family: -apple-system, Helvetica, Arial, sans-serif; color: #1f2937; font-size: 12px; padding: 24px; }
  h1 { font-size: 22px; margin: 0 0 2px; }
  h2 { font-size: 14px; margin: 22px 0 8px; padding-bottom: 4px; border-bottom: 2px solid #f59e0b; }
  .sub { color: #6b7280; margin: 0 0 14px; }
  .facts { display: flex; flex-wrap: wrap; gap: 6px 22px; margin: 0 0 6px; }
  .facts div { min-width: 120px; }
  .facts b { display: block; font-size: 10px; text-transform: uppercase; color: #6b7280; letter-spacing: .04em; }
  table { width: 100%; border-collapse: collapse; }
  th { text-align: left; font-size: 10px; text-transform: uppercase; color: #6b7280; padding: 6px 8px; background: #f3f4f6; }
  td { padding: 6px 8px; border-bottom: 1px solid #e5e7eb; vertical-align: top; }
  .num { text-align: right; white-space: nowrap; }
  .total td { font-weight: bold; border-top: 2px solid #1f2937; border-bottom: none; }
  ul { margin: 2px 0 0; padding-left: 16px; }
  .muted { color: #6b7280; }
  .foot { margin-top: 28px; font-size: 10px; color: #6b7280; }
`;

function page(title: string, body: string): string {
  const today = new Date().toLocaleDateString(undefined, { year: "numeric", month: "long", day: "numeric" });
  return `<!DOCTYPE html><html><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><style>${STYLE}</style></head><body>
    ${body}
    <p class="foot">${esc(title)} · generated by Project-Panday on ${esc(today)}. All prices are estimates, not quotes.</p>
  </body></html>`;
}

const fact = (label: string, value: string | number) => `<div><b>${esc(label)}</b>${esc(value)}</div>`;

/**
 * The plan and its budget: what the AI proposed (or the homeowner approved), ready to print or share.
 * Plans saved before some fields existed come back partial, so anything missing prints as empty.
 */
export function planPdfHtml(saved: Partial<ConstructionPlan>): string {
  const plan: ConstructionPlan = {
    projectTitle: "Project plan",
    location: "",
    areaSqm: 0,
    floors: 0,
    bedrooms: 0,
    bathrooms: 0,
    designStyle: "—",
    budget: 0,
    timelineMonths: 0,
    phases: [],
    budgetBreakdown: [],
    materials: [],
    exteriorConcept: "",
    interiorConcept: "",
    totalEstimate: 0,
    ...saved,
  };
  const materialsTotal = plan.materials.reduce((sum, m) => sum + m.qty * m.unitPrice, 0);
  const breakdownTotal = plan.budgetBreakdown.reduce((sum, b) => sum + b.amount, 0);
  const garage = plan.garageCars ? `${plan.garageCars}-car garage` : "No garage";
  const gap = plan.budget > 0 ? plan.budget - plan.totalEstimate : null;

  const body = `
    <h1>${esc(plan.projectTitle)}</h1>
    <p class="sub">${esc(plan.location || "Location not set")} · ${esc(plan.designStyle)} style</p>
    <div class="facts">
      ${fact("Floor area", `${plan.areaSqm} sqm`)}
      ${fact("Floors", plan.floors)}
      ${fact("Bedrooms / baths", `${plan.bedrooms} / ${plan.bathrooms}`)}
      ${fact("Garage", garage)}
      ${fact("Timeline", `${plan.timelineMonths} months`)}
    </div>
    <div class="facts">
      ${fact("Your budget", plan.budget > 0 ? peso(plan.budget) : "Not set")}
      ${fact("AI estimate", peso(plan.totalEstimate))}
      ${gap === null ? "" : fact(gap >= 0 ? "To spare" : "Short by", peso(Math.abs(gap)))}
    </div>

    <h2>Budget breakdown</h2>
    <table>
      <tr><th>Category</th><th class="num">Amount</th><th class="num">Share</th></tr>
      ${plan.budgetBreakdown
        .map(
          (b) =>
            `<tr><td>${esc(b.category)}</td><td class="num">${esc(peso(b.amount))}</td><td class="num">${
              breakdownTotal > 0 ? Math.round((b.amount / breakdownTotal) * 100) : 0
            }%</td></tr>`
        )
        .join("")}
      <tr class="total"><td>Total estimate</td><td class="num">${esc(peso(breakdownTotal))}</td><td></td></tr>
    </table>

    <h2>Phases</h2>
    <table>
      <tr><th>Phase</th><th class="num">Weeks</th><th class="num">Share</th><th>Tasks</th></tr>
      ${plan.phases
        .map(
          (p) =>
            `<tr><td>${esc(p.name)}</td><td class="num">${p.durationWeeks ?? "—"}</td><td class="num">${esc(p.percentComplete)}%</td><td><ul>${p.tasks
              .map((t) => `<li>${esc(t)}</li>`)
              .join("")}</ul></td></tr>`
        )
        .join("")}
    </table>

    <h2>Materials</h2>
    <table>
      <tr><th>Material</th><th class="num">Qty</th><th class="num">Unit price</th><th class="num">Total</th><th>Source</th></tr>
      ${plan.materials
        .map(
          (m) =>
            `<tr><td>${esc(m.material)}<br /><span class="muted">${esc(m.phase ?? m.category)}</span></td><td class="num">${esc(m.qty)} ${esc(m.unit)}</td><td class="num">${esc(
              peso(m.unitPrice)
            )}</td><td class="num">${esc(peso(m.qty * m.unitPrice))}</td><td>${m.supplierName ? esc(m.supplierName) : '<span class="muted">AI estimate</span>'}</td></tr>`
        )
        .join("")}
      <tr class="total"><td colspan="3">Itemized materials</td><td class="num">${esc(peso(materialsTotal))}</td><td></td></tr>
    </table>

    <h2>Design concept</h2>
    <p><b>Exterior.</b> ${esc(plan.exteriorConcept)}</p>
    <p><b>Interior.</b> ${esc(plan.interiorConcept)}</p>`;

  return page(`${plan.projectTitle} plan`, body);
}

/** A material request: what's being ordered, from whom, and what it's expected to cost. */
export function materialRequestPdfHtml(request: MaterialRequest): string {
  const confirmed = request.confirmedTotal > 0;
  const body = `
    <h1>Material request #${esc(request.id)}</h1>
    <p class="sub">${esc(request.project.title)}${request.project.location ? ` · ${esc(request.project.location)}` : ""}</p>
    <div class="facts">
      ${fact("Status", request.status.replace(/_/g, " "))}
      ${fact("Contractor", request.contractor.name)}
      ${fact("Homeowner", request.homeowner.name)}
      ${request.phase ? fact("Phase", request.phase.name) : ""}
      ${request.neededBy ? fact("Needed by", request.neededBy) : ""}
    </div>

    <h2>Items</h2>
    <table>
      <tr><th>Material</th><th>Supplier</th><th class="num">Qty</th><th class="num">Unit price</th><th class="num">Subtotal</th></tr>
      ${request.items
        .map((item) => {
          const price = item.confirmedUnitPrice ?? item.estimatedUnitPrice;
          const subtotal = item.confirmedSubtotal ?? item.estimatedSubtotal;
          return `<tr><td>${esc(item.materialName)}</td><td>${item.supplierName ? esc(item.supplierName) : '<span class="muted">—</span>'}</td><td class="num">${esc(item.quantity)} ${esc(item.unit)}</td><td class="num">${esc(
            peso(price)
          )}</td><td class="num">${esc(peso(subtotal))}</td></tr>`;
        })
        .join("")}
      <tr class="total"><td colspan="4">${confirmed ? "Confirmed total" : "Estimated total"}</td><td class="num">${esc(
        peso(confirmed ? request.confirmedTotal : request.estimatedTotal)
      )}</td></tr>
    </table>
    ${request.notes ? `<h2>Notes</h2><p>${esc(request.notes)}</p>` : ""}
    ${request.decisionReason ? `<h2>Homeowner's decision</h2><p>${esc(request.decisionReason)}</p>` : ""}`;

  return page(`Material request #${request.id}`, body);
}
